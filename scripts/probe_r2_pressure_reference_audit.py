#!/usr/bin/env python3
"""Lightweight analytic probe for R3.16 pressure-reference module."""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime

import numpy as np

WS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(WS, "results", "round2_pressure_reference_closure")
sys.path.insert(0, WS)


def close(a, b, tol=1e-12):
    return a is not None and b is not None and abs(float(a) - float(b)) <= tol


def metrics(pred, ref):
    pred = np.asarray(pred, float)
    ref = np.asarray(ref, float)
    bias = float(pred.mean() - ref.mean())
    cp = pred - pred.mean()
    cr = ref - ref.mean()
    denom = float(np.linalg.norm(cr))
    return {
        "bias": bias,
        "raw_re": (float(np.linalg.norm(pred - ref) / np.linalg.norm(ref))
                        if np.linalg.norm(ref) > 0 else None),
        "centered_re": (float(np.linalg.norm(cp - cr) / denom)
                        if denom > 0 else None),
        "centered_denominator": denom,
        "identity_residual": float(
            np.linalg.norm(pred - ref) ** 2
            - np.linalg.norm(cp - cr) ** 2 - len(ref) * bias * bias),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=OUT)
    args = ap.parse_args()
    out = os.path.abspath(args.out_dir)
    os.makedirs(out, exist_ok=True)
    rng = np.random.default_rng(20261023)
    ref = rng.normal(size=5000)
    pred = ref + rng.normal(scale=0.05, size=5000)
    base = metrics(pred, ref)
    checks = {}
    # Different constant shifts to prediction and reference: centered RE unchanged.
    for cp, cr in ((1.0, -2.0), (0.125, 0.0), (-3.0, 0.5)):
        m = metrics(pred + cp, ref + cr)
        checks[f"centered_invariant_{cp}_{cr}"] = close(
            m["centered_re"], base["centered_re"])
        checks[f"raw_denominator_changes_{cp}_{cr}"] = not close(
            m["raw_re"], base["raw_re"])
    checks["identity"] = abs(base["identity_residual"]) < 1e-10
    # zero centered reference must be undefined, no epsilon fudge
    zero = metrics(pred, np.zeros_like(ref))
    checks["zero_center_undefined"] = zero["centered_re"] is None
    # exact integral zero shift is one constant; centered residual must vanish.
    p_area = 2.5
    p_point = ref + p_area
    p_int = p_point - p_point.mean()
    checks["integral_shift_only"] = close(metrics(p_int, ref)["centered_re"],
                                          metrics(p_point, ref)["centered_re"])
    checks["integral_mean_zero"] = abs(float(p_int.mean())) < 1e-12
    checks["all_pass"] = all(checks.values())
    report = {"task": "R3.16 pressure reference analytic probe",
              "created_local": datetime.now().astimezone().isoformat(timespec="seconds"),
              "checks": checks,
              "base_metrics": base,
              "zero_metrics": zero,
              "note": "analytic only; real FEM exact-gauge evidence is generated by SLURM"}
    p = os.path.join(out, "probe_report.json")
    if os.path.exists(p):
        raise SystemExit(f"[refuse] exists: {p}")
    with open(p, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, ensure_ascii=False)
    print(json.dumps(checks, indent=2), flush=True)
    if not checks["all_pass"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
